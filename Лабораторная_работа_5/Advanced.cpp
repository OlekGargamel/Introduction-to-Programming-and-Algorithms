// Функция: y = 5 / (x * (x - 2)). Обработка точек разрыва (x=0 и x=2)

#include <iostream> 
#include <iomanip>
#include <cmath>
#include <limits> // Для numeric_limits

using namespace std;

int main() {
	setlocale(LC_ALL, "RU");

	//Объявление переменных
	double a, b, h;

	//Ввод начала интервала
	cout << "Введите начало интервала: ";
	cin >> a;
	while (cin.fail()) {  //Цикл с проверкой на корректный ввод
		cout << "Ошибка ввода! ";  //Предупреждение об ошибке
		cin.clear(); //Сброс флага ошибки
		cin.ignore(numeric_limits<streamsize>::max(), '\n'); //Выбрасываем содержание из буфера
		cin >> a;
	}

	//Ввод конца интервала
	cout << "Введите конец интервала: ";
	cin >> b;
	while (cin.fail() || b <= a) {  //Цикл с проверкой на корректный ввод
		cout << "Ошибка ввода! ";  //Предупреждение об ошибке
		cin.clear(); //Сброс флага ошибки
		cin.ignore(numeric_limits<streamsize>::max(), '\n'); //Выбрасываем содержание из буфера
		cin >> b;
	}

	//Ввод шага
	cout << "Введите шаг: ";
	cin >> h;
	while (cin.fail() || h <= 0) {  //Цикл с проверкой на корректный ввод
		cout << "Ошибка ввода! ";  //Предупреждение об ошибке
		cin.clear(); //Сброс флага ошибки
		cin.ignore(numeric_limits<streamsize>::max(), '\n'); //Выбрасываем содержание из буфера
		cin >> h;
	}

	//Демонстрация данной функции
	cout << "======================================================" << endl;
	cout << "	x	|	y = 5 / (x * (x - 2))" << endl;
	cout << "======================================================" << endl;

	cout << fixed << setprecision(4);

	//Счётчик точек разрыва
	int kolRazryv = 0;

	//Цикл для вычисления
	for (double x = a; x <= b + 1e-9; x = x + h) { //Пока x находится в диапазоне (a,b) цикл выполняется
		//Проверяем точки разрыва: x = 0 и x = 2 (используем abs из-за погрешности double)
		if (abs(x) < 1e-9 || abs(x - 2.0) < 1e-9) {
			cout << setw(8) << x << "|" << "Разрыв (деление на ноль)" << endl; //Граничное значение
			kolRazryv++; //Увеличиваем счётчик разрывов
		}
		else {
			double znam = x * (x - 2); //Вычисление знаменателя
			double y = 5.0 / znam; //Вычисление значения функции
			cout << setw(8) << x << "|" << setw(12) << y << endl; //Вывод результата
		}
	}

	cout << "======================================================" << endl;
	cout << "Разрывов найдено: " << kolRazryv << endl; //Вывод количества разрывов

	return 0; //Успешное завершение
}
