#include <iostream> 
#include <iomanip>
#include <cmath>

using namespace std;

int main() {
	setlocale(LC_ALL, "RU");

	//Объявление переменных
	double a, b, h;


	//Ввод начала интервала
	cout << "Введите начало интервала: ";
	cin >> a;
	while (cin.fail() || a == 0) {  //Цикл с проверкой на корректный ввод
		cout << "Ошибка ввода! ";  //Предупреждение об ошибке
		cin.clear(); //Сброс флага ошибки
		cin.ignore(numeric_limits<streamsize>::max(), '\n'); //Выбрасываем содержание из буфера
		cin >> a;
	}

	//Ввод конца интервала
	cout << "Введите конец интервала: ";
	cin >> b;
	while (cin.fail() || b == 0 || b <= a) {  //Цикл с проверкой на корректный ввод
		cout << "Ошибка ввода! ";  //Предупреждение об ошибке
		cin.clear(); //Сброс флага ошибки
		cin.ignore(numeric_limits<streamsize>::max(), '\n'); //Выбрасываем содержание из буфера
		cin >> b;
	}


	//Ввод шага
	cout << "Введите шаг: ";
	cin >> h;
	while (cin.fail() || h <= 0) {  //Цикл с проверкой на корректный ввод
		cout << "Ошибка ввода! ";  //Предупреждение об ошибке
		cin.clear(); //Сброс флага ошибки
		cin.ignore(numeric_limits<streamsize>::max(), '\n'); //Выбрасываем содержание из буфера
		cin >> h;
	}

	//Демонстрация данной фукнции
	cout << "===============================================" << endl;
	cout << "	x	|	y = 5 / x" << endl;
	cout << "===============================================" << endl;

	cout << fixed << setprecision(4);

	//Цикл	для вычисления
	for (double x = a; x <= b + 1e-9; x = x + h) { //Пока x находится в диапазоне (a,b) цикл выполняется
		if (abs(x) < 1e-9) {
			cout << x << "|" << "Не существует функция" << endl; //Граничное значение
		}
		else {
			double y = 5.0 / x; //Вычисление значения функции
			cout << x << "|" << y << endl; //Вывод результата
		}
	}

	cout << "===============================================";

	return 0; //Успешное завершение
}
